"""E9: the same loop with LLM raters instead of a hand-written simulated user.

Data: data/llm_ratings.json (see llm_raters.py). For each rater and each of 40 real leases:
p = rating from the listing page, f = mean of two post-viewing ratings (hidden truth),
y = a third post-viewing rating (what the optimiser observes).

Nothing about the surprise f - p is generated by our GP here, so the model is
misspecified in whatever way the LLM's behaviour makes it. Hyperparameters, the prior-mean
correction, lambda and the fixed-K baseline are all fitted on OTHER raters (two-fold
cross-fitting), never on the rater being evaluated.
"""
import json

import numpy as np
from scipy.optimize import minimize

from common import ROOT, save
from housebo import stopping as st
from housebo.metrics import fmt, mean_se, paired
from housebo.policies import run_trajectory
from housebo.simulator import Kernel, Problem, _moi_table, decorrelate

KMAX = 20
LAMS = [0.01, 0.015, 0.02, 0.03, 0.05, 0.08, 0.12, 0.16, 0.2, 0.3]


def load():
    d = json.loads((ROOT / "data" / "llm_ratings.json").read_text())
    rows, km, num = _moi_table()
    out = []
    for r in d["raters"]:
        idx = np.array(r["listings"])
        loc = km[idx]
        dist = np.linalg.norm(loc, axis=1)
        own = np.array([rows[i]["rental_type"] == "獨立套房" for i in idx], float)
        # Kernel features: only what the listing page shows.
        Z = np.column_stack([num["rent"][idx], num["size_ping"][idx], 10 + 4 * dist,
                             num["furnished"][idx], own])
        sd = Z.std(0)
        Z = (Z - Z.mean(0)) / np.where(sd > 0, sd, 1.0)
        p, A, B, C = (np.array(r[k]) for k in "pABC")
        out.append(dict(Z=Z, loc=loc, cost=0.75 + 2 * dist / 12.0, p=p, f=(A + B) / 2, y=C,
                        rent=num["rent"][idx], order=np.random.default_rng(r["rater"]).permutation(len(idx))))
    return d, out


def fit(train):
    """Prior-mean correction, noise and kernel hyperparameters from other raters."""
    delta = np.concatenate([r["y"] - r["p"] for r in train])
    pc = np.concatenate([r["p"] - r["p"].mean() for r in train])
    shrink, shift = np.polyfit(pc, delta, 1)            # delta ~ shift + shrink * (p - mean p)
    noise_var = np.mean([np.var(r["y"] - r["f"]) for r in train]) / 1.5   # var(C - mean(A,B)) = 1.5 s^2

    def nll(theta):
        k = Kernel(*np.exp(theta))
        tot = 0.0
        for r in train:
            res = r["y"] - r["p"] - shift - shrink * (r["p"] - r["p"].mean())
            S = k.matrix(r["Z"], r["loc"]) + noise_var * np.eye(len(res))
            L = np.linalg.cholesky(S)
            a = np.linalg.solve(L, res)
            tot += 0.5 * a @ a + np.log(np.diag(L)).sum()
        return tot

    best = min((minimize(nll, np.log(x0), method="L-BFGS-B", bounds=[(-4, 2)] * 4)
                for x0 in ([0.3, 0.8, 1.5, 0.7], [0.5, 0.5, 4.0, 1.2], [0.2, 1.2, 0.8, 1.0])),
               key=lambda o: o.fun)
    return dict(shift=float(shift), shrink=float(shrink), noise_var=float(noise_var),
                kernel=Kernel(*np.exp(best.x)))


def problem(r, hp, lam, variant="fitted"):
    m = r["p"] + hp["shift"] + hp["shrink"] * (r["p"] - r["p"].mean())
    K = hp["kernel"].matrix(r["Z"], r["loc"])
    nv = hp["noise_var"]
    if variant == "independent":
        K = decorrelate(K)
    if variant == "naive":           # take listing ratings at face value, default hyperparameters
        m, K, nv = r["p"].copy(), Kernel().matrix(r["Z"], r["loc"]), 0.4**2
    return Problem(Z=r["Z"], raw={}, loc=r["loc"], cost=r["cost"], p=r["p"], m=m, f=r["f"],
                   eps=r["y"] - r["f"], K_model=K, noise_var_model=nv, lam=lam, order_random=r["order"])


def choose_lambda(train, hp):
    """Same rule as the main experiments: median viewings of the main method closest to 6."""
    def med(lam):
        n = [st.cost_aware(run_trajectory(problem(r, hp, lam), "pbgi:kg"), "kg") for r in train]
        return np.median(n), np.mean(n)
    stats = {lam: med(lam) for lam in LAMS}
    return min(LAMS, key=lambda l: (abs(stats[l][0] - 6), abs(stats[l][1] - 6))), stats


def evaluate(test, train, hp, lam, _unused=None):
    res = []
    # fixed-K baselines tuned on the training raters only
    def best_k(sel, variant="fitted"):
        V = np.array([run_trajectory(problem(r, hp, lam, variant), sel, KMAX).V for r in train])
        return int(np.argmax(V.mean(0))) + 1
    k_pbgi, k_prior = best_k("pbgi:kg"), best_k("prior")
    for r in test:
        T = {s: run_trajectory(problem(r, hp, lam), s) for s in ("pbgi:kg", "ei", "prior", "random")}
        Ti = run_trajectory(problem(r, hp, lam, "independent"), "pbgi:kg")
        Tn = run_trajectory(problem(r, hp, lam, "naive"), "pbgi:kg")
        main, tau = T["pbgi:kg"], st.cost_aware(T["pbgi:kg"], "kg")
        tau_l = st.cost_aware(run_trajectory(problem(r, hp, lam), "pbgi:latent"), "latent")
        Tl = run_trajectory(problem(r, hp, lam), "pbgi:latent")
        row = {
            "main": (main.V[tau - 1], tau, main.hours[tau - 1]),
            "hindsight": (main.V.max(), st.hindsight(main), main.hours[st.hindsight(main) - 1]),
            "fixedK": (main.V[k_pbgi - 1], k_pbgi, main.hours[k_pbgi - 1]),
            "ei_stop": (lambda t: (T["ei"].V[t - 1], t, T["ei"].hours[t - 1]))(st.cost_aware(T["ei"], "kg")),
            "orig_index": (Tl.V[tau_l - 1], tau_l, Tl.hours[tau_l - 1]),
            "independent": (lambda t: (Ti.V[t - 1], t, Ti.hours[t - 1]))(st.cost_aware(Ti, "kg")),
            "naive_prior": (lambda t: (Tn.V[t - 1], t, Tn.hours[t - 1]))(st.cost_aware(Tn, "kg")),
            "listing_top5": (T["prior"].V[4], 5, T["prior"].hours[4]),
            "listing_bestK": (T["prior"].V[k_prior - 1], k_prior, T["prior"].hours[k_prior - 1]),
            "random5": (T["random"].V[4], 5, T["random"].hours[4]),
            "immediate": (main.V[0], 1, main.hours[0]),
        }
        assert all(row[k][0] <= row["hindsight"][0] + 1e-12 for k in ("main", "fixedK", "immediate"))
        res.append(row)
    return res


LABEL = {"main": "GP + fair value + cost-aware stop (main)", "hindsight": "  same order, per-rater hindsight (bound)",
         "fixedK": "  same order, fixed K (K tuned on other raters)", "ei_stop": "EI order + cost-aware stop",
         "orig_index": "original index (ignores rating noise)", "independent": "no cross-listing learning",
         "naive_prior": "listing ratings at face value, default kernel",
         "listing_top5": "visit the 5 best-looking", "listing_bestK": "visit the K best-looking (K tuned)",
         "random5": "5 random viewings", "immediate": "one viewing"}

def run(d, R, title):
    folds = [R[0::2], R[1::2]]
    rows, info = [], []
    for te, tr in ((0, 1), (1, 0)):
        hp = fit(folds[tr])
        lam, stats = choose_lambda(folds[tr], hp)
        rows += [{k: v + (v[0] + lam * v[2],) for k, v in r.items()} for r in evaluate(folds[te], folds[tr], hp, lam)]
        k = hp["kernel"]
        info.append(dict(lam=lam, shift=hp["shift"], shrink=hp["shrink"], noise_sd=hp["noise_var"]**0.5,
                         s_lin=k.s_lin, s_sp=k.s_sp, ell=k.ell, s_idio=k.s_idio))
        print(f"fold fitted on {len(folds[tr])} raters: " + ", ".join(f"{a}={b:.3f}" for a, b in info[-1].items()))
    V = {k: np.array([r[k][0] for r in rows]) for k in LABEL}
    N = {k: np.array([r[k][1] for r in rows]) for k in LABEL}
    H = {k: np.array([r[k][2] for r in rows]) for k in LABEL}
    Q = {k: np.array([r[k][3] for r in rows]) for k in LABEL}
    sur = np.concatenate([r["f"] - r["p"] for r in R])
    print(f"\n== E9 [{title}]: {len(rows)} LLM raters ({d['model']}), 40 real leases each ==")
    print(f"listing-page vs post-viewing rating: mean surprise {sur.mean():+.2f}, sd {sur.std():.2f}")
    print(f"{'policy':50s} {'V':>16s} {'viewings':>9s} {'hours':>6s} | main - this: {'V':>14s} {'quality':>16s} {'hours':>14s}")
    out = {}
    for k, lab in LABEL.items():
        dd, dq, dh = paired(V["main"], V[k]), paired(Q["main"], Q[k]), paired(H["main"], H[k])
        tail = "" if k == "main" else f"{fmt(dd):>16s} {fmt(dq):>16s} {fmt(dh, 2):>14s}"
        print(f"{lab:50s} {V[k].mean():7.3f} ± {mean_se(V[k])[1]:.3f} {N[k].mean():9.2f} {H[k].mean():6.2f} | {tail}")
        out[k] = dict(V=mean_se(V[k]), viewings=mean_se(N[k]), hours=mean_se(H[k]), quality=mean_se(Q[k]),
                      V_main_minus_this=dd, quality_main_minus_this=dq, hours_main_minus_this=dh)
    return dict(n_raters=len(rows), folds=info, surprise_mean=float(sur.mean()),
                surprise_sd=float(sur.std()), results=out)


if __name__ == "__main__":
    d, R = load()
    # Sample size was increased once (80 -> 300) after looking at the first 80. Report the
    # first batch, the new batch alone, and the pooled result.
    res = {name: run(d, sub, name) for name, sub in
           (("first 80", R[:80]), ("new 220 only", R[80:]), ("pooled 300", R))}
    save("e9_llm", dict(model=d["model"], **{k.replace(" ", "_"): v for k, v in res.items()}))
